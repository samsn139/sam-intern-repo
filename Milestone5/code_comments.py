# This function calculates the area of a circle.
# It uses the formula: Area = π * radius^2
# We use a constant value for π (3.14159) for simplicity.
def calculate_area(radius):
    PI = 3.14159  # π, the mathematical constant representing the ratio of a circle's circumference to its diameter
    return PI * radius * radius  # Area = π * radius^2

